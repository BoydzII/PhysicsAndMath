function showLesson(tid) {
  const t = topicOf(tid);
  if (!t) return;
  openModal({
    title: (t.icon || '') + ' ' + chLabel(t) + ' · ' + t.name,
    bodyHTML: lessonHTML(tid),
    buttons: [{ label: 'ปิด' },
              { label: 'เริ่มฝึกขั้นนี้ 10 ข้อ', cls: 'primary', act: (close) => { close(); practiceStep(tid); } }]
  });
}
function practiceStep(tid) {
  const t = topicOf(tid);
  if (!t || needLearnerName()) return;
  const q = createQuiz({
    title: chLabel(t) + ' · ' + t.short + ' — ' + thDate(Date.now()),
    topics: [tid], subs: [], counts: Object.assign({}, PATH_COUNTS), kind: 'practice',
    seed: Math.floor(Math.random() * 2000000000) + 1
  });
  if (q.error) { toast(q.error, 'bad'); return; }
  DB.quizzes.push(q);
  DB.cur.quizId = q.id;
  save(true);
  toast('สร้างชุดฝึก' + chLabel(t) + 'แล้ว — ทำให้ได้ ' + PATH_PASS + '% ขึ้นไปเพื่อผ่านขั้นนี้', 'ok');
  startQuiz(q.id);
}
function pathBind() {
  $$('[data-plesson]').forEach(b => b.addEventListener('click', () => showLesson(Number(b.dataset.plesson))));
  $$('[data-ppractice]').forEach(b => b.addEventListener('click', () => practiceStep(Number(b.dataset.ppractice))));
}
