/** สถานะของทุกขั้นจากผลที่ทำเสร็จแล้ว — { tid: { best, n, pass } } */
function pathStatus() {
  const st = {};
  TOPICS.forEach(t => { st[t.id] = { best: null, n: 0, pass: false }; });
  learnerAttempts().forEach(a => {
    let r;
    try { r = analyze(a); } catch (e) { return; }
    Object.keys(r.byTopic).forEach(k => {
      const o = r.byTopic[k], s = st[k];
      if (!s || !o.max) return;
      s.n += o.max;
      if (o.max >= PATH_MIN) {
        if (s.best == null || o.pct > s.best) s.best = o.pct;
        if (o.pct >= PATH_PASS) s.pass = true;
      }
    });
  });
  return st;
}
/** ขั้นแนะนำ = ขั้นแรกตามลำดับที่ยังไม่ผ่าน */
function pathNext(st) {
  const order = TOPICS.slice().sort((a, b) => a.ch - b.ch);
  const t = order.find(x => !st[x.id].pass);
  return t ? t.id : null;
}
